# Random Forest Model Evaluation
# Why: Calculate several performance measures together so we can
# fairly compare the Random Forest with the logistic regression model.
rf_actual <- test_data$Purchased_Next_30_Days
rf_TP <- sum(rf_actual == 1 & rf_prediction == 1)
rf_TN <- sum(rf_actual == 0 & rf_prediction == 0)
rf_FP <- sum(rf_actual == 0 & rf_prediction == 1)
rf_FN <- sum(rf_actual == 1 & rf_prediction == 0)
rf_accuracy <- (rf_TP + rf_TN) / length(rf_actual)
rf_sensitivity <- rf_TP / (rf_TP + rf_FN)
rf_specificity <- rf_TN / (rf_TN + rf_FP)
rf_precision <- rf_TP / (rf_TP + rf_FP)
rf_f1 <- 2 * (rf_precision * rf_sensitivity) / (rf_precision + rf_sensitivity)
rf_metrics <- data.frame(Accuracy = rf_accuracy,Sensitivity = rf_sensitivity,Specificity = rf_specificity,Precision = rf_precision,F1_Score = rf_f1)
rf_metrics

