# 10. Define Prediction Period
# Why: Set a cutoff date so we can use past customer behavior
# to predict whether they purchase in the following period.
cutoff_date <- as.POSIXct("2011-11-01")
cutoff_date

# Create Historical Customer Data
# Why: Use only past transactions to create the information
# that the ML model will use for prediction.
historical_data <- retail_clean %>%filter(InvoiceDate < cutoff_date)
dim(historical_data)

#---------------------------- Interpretation-------------------------------
# We now have 316,049 transaction records from before November 1, 2011.
# These records represent the past customer behavior that we will use
# to build our ML prediction features.

#  Create Historical Customer Features
# Why: Summarize each customer's past purchasing behavior
# so the ML model can learn from their previous activity.
customer_features <- historical_data %>%group_by(CustomerID) %>%summarise(Recency = as.numeric(difftime(cutoff_date,max(InvoiceDate),units = "days")),Frequency = n_distinct(InvoiceNo),Monetary = sum(Revenue),.groups = "drop")
head(customer_features)

#----------------------------- Interpretation-----------------------------------
# The table summarizes each customer's past behavior before November 1, 2011.
# For example, customer 12347 purchased recently, made 6 orders, and spent
# about £4,085. These past behaviors will be used as inputs for our ML model.

# Create Future Purchase Target
# Why: Create the answer that our ML model will learn to predict:
# whether a customer makes a purchase in the 30 days after the cutoff date.
future_data <- retail_clean %>%filter(InvoiceDate >= cutoff_date,InvoiceDate < cutoff_date + days(30))
future_customers <- future_data %>%distinct(CustomerID) %>%mutate(Purchased_Next_30_Days = 1)
customer_features <- customer_features %>%left_join(future_customers,by = "CustomerID") %>%mutate(Purchased_Next_30_Days = ifelse(is.na(Purchased_Next_30_Days),0,Purchased_Next_30_Days))
table(customer_features$Purchased_Next_30_Days)

# ---------------------------Interpretation------------------------------------------
# Out of 3,974 customers, 1,341 made at least one purchase during the
# 30 days after November 1, 2011, while 2,633 customers did not purchase.
# This gives us a binary target with two groups: purchased and did not purchase.

# Check Target Proportions
# Why: Check whether the two target groups are reasonably balanced
# before training the ML model.
prop.table(table(customer_features$Purchased_Next_30_Days))

# Interpretation:
# About 66.3% of customers did not purchase in the next 30 days,
# while about 33.7% did purchase. The two groups are not perfectly equal,
# but the difference is reasonable, so we do not have a severe class
# imbalance problem.

# Split Data into Training and Testing Sets
# Why: Keep some customers separate so we can test how well
# the ML model predicts customers it has not seen before.
set.seed(123)
train_index <- sample(1:nrow(customer_features),size = 0.8 * nrow(customer_features))
train_data <- customer_features[train_index, ]
test_data <- customer_features[-train_index, ]
dim(train_data)
dim(test_data)
dim(test_data)

# First ML Model - Logistic Regression
# Why: Use logistic regression to learn how past customer behavior
# can predict whether a customer will purchase in the next 30 days.
ml_model <- glm(Purchased_Next_30_Days ~ Recency + Frequency + Monetary,data = train_data,family = binomial)
summary(ml_model)

#---------------------------- Interpretation-------------------------------
# The model shows that Recency and Frequency are important predictors of
# future purchasing. Customers who purchased more recently and made more
# previous orders are more likely to purchase again. Monetary is not
# statistically significant in this model, suggesting that past spending
# alone is not a strong predictor of purchasing in the next 30 days.

# Predict Future Purchases
# Why: Use the trained ML model to estimate the probability
# that each new customer will purchase in the next 30 days.
test_data$Purchase_Probability <- predict(ml_model,newdata = test_data,type = "response")
head(test_data[, c("CustomerID","Recency","Frequency","Monetary","Purchase_Probability")])

#---------------------------- Interpretation----------------------------------------
# The model gives each customer a probability of making a purchase in the
# next 30 days. Customers with more recent and frequent purchases generally
# receive higher predicted probabilities.

# Convert Probabilities into Predictions
# Why: Convert the predicted probabilities into Yes/No decisions
# so we can compare the model's predictions with the actual outcomes.
test_data$Predicted_Purchase <- ifelse(test_data$Purchase_Probability >= 0.5,1,0)
table(test_data$Predicted_Purchase)

#-------------------------- Interpretation-----------------------------------
# Using a 0.5 probability threshold, the model predicts that 112 customers
# will purchase in the next 30 days, while 683 customers will not purchase.
# We now need to compare these predictions with what actually happened.

# Confusion Matrix
# Why: Compare the model's predictions with the actual customer outcomes
# to see how well the ML model performed on unseen customers.
table(Actual = test_data$Purchased_Next_30_Days,Predicted = test_data$Predicted_Purchase)

#----------------------------- Interpretation------------------------------
# The model correctly predicted 497 customers who did not purchase and
# 84 customers who did purchase. However, it missed 186 customers who
# actually purchased. This means the model is better at identifying
# customers who will not purchase than customers who will purchase.

# Model Accuracy
# Why: Measure the overall percentage of predictions that were correct.
accuracy <- mean(test_data$Predicted_Purchase == test_data$Purchased_Next_30_Days)
accuracy

#------------------------------ Interpretation-----------------------------
# The model correctly classified about 73.1% of the customers in the
# test dataset. This gives a reasonable overall result, but accuracy
# alone does not tell us how well the model identifies customers who
# actually purchase.

# Sensitivity (Recall)
# Why: Measure how well the model identifies customers who actually
# make a purchase in the next 30 days.
true_positive <- sum(test_data$Purchased_Next_30_Days == 1 &test_data$Predicted_Purchase == 1)
actual_positive <- sum(test_data$Purchased_Next_30_Days == 1)
sensitivity <- true_positive / actual_positive
sensitivity

#---------------------------- Interpretation----------------------------------
# The model correctly identified about 31.1% of the customers who actually
# purchased in the next 30 days. This means the model missed many potential
# purchasers, so its ability to identify future buyers is currently limited.

# Specificity
# Why: Measure how well the model identifies customers who do not
# make a purchase in the next 30 days.
true_negative <- sum(test_data$Purchased_Next_30_Days == 0 &test_data$Predicted_Purchase == 0)
actual_negative <- sum(test_data$Purchased_Next_30_Days == 0)
specificity <- true_negative / actual_negative
specificity

#---------------------------- Interpretation-----------------
# The model correctly identified about 94.7% of the customers who did not
# purchase in the next 30 days. This shows that the model is much better at
# identifying non-purchasers than identifying future purchasers.

# Precision
# Why: Measure how often the customers predicted to purchase
# actually make a purchase.
true_positive <- sum(test_data$Purchased_Next_30_Days == 1 &test_data$Predicted_Purchase == 1)
predicted_positive <- sum(test_data$Predicted_Purchase == 1)
precision <- true_positive / predicted_positive
precision

#--------------------------- Interpretation---------------------------------
# When the model predicts that a customer will purchase, it is correct
# about 75% of the time. This is a good result, although the model still
# misses many customers who actually purchase.

# F1 Score
# Why: Combine precision and sensitivity into one measure
# to evaluate how well the model identifies future purchasers.
f1_score <- 2 * (precision * sensitivity) / (precision + sensitivity)
f1_score

# -----------------------------Interpretation-------------------------------
# The F1 score is about 0.44, showing that the model has a reasonable
# balance between precision and sensitivity, but its ability to identify
# future purchasers still needs improvement.

# ROC Curve and AUC
# Why: Evaluate how well the model separates customers who purchase
# from customers who do not across different probability thresholds.
